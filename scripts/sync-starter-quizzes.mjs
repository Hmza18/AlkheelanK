#!/usr/bin/env node
/**
 * Bundle full starter quiz payloads into the client so "Copy to My Quizzes"
 * never depends on the game server (works on Vercel / offline server).
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { getStarterForCopy } from "../server/src/quizzes.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, "../client/src/data/starterCopyData.js");

const IDS = [
  "house-party",
  "movie-night",
  "general-knowledge",
  "kids-corner",
  "around-the-world",
  "family-faceoff",
];

const data = {};
for (const id of IDS) {
  const quiz = getStarterForCopy(id);
  if (!quiz) {
    console.error(`Missing starter quiz: ${id}`);
    process.exit(1);
  }
  data[id] = quiz;
}

const body = `/** Auto-generated by scripts/sync-starter-quizzes.mjs — do not edit. */
export const STARTER_COPY_DATA = ${JSON.stringify(data, null, 2)};
`;

fs.writeFileSync(OUT, body, "utf8");
console.log(`Synced ${IDS.length} starter quiz(es) → client/src/data/starterCopyData.js`);
